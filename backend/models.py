"""
SynthLeak Relational Database Models.
Implements the storage layer conforming strictly to CONTRACT.md schemas.
Entities: Pipeline, Sensor, Alert, WorkOrderTicket.
"""

from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    String,
    Float,
    Integer,
    Boolean,
    ForeignKey,
    JSON,
    Text,
)
from sqlalchemy.orm import relationship
from backend.database import Base


def utc_now_iso() -> str:
    """Return current UTC timestamp in ISO 8601 format."""
    return datetime.now(timezone.utc).isoformat()


class PipelineModel(Base):
    """Monitored municipal water distribution pipeline segment."""
    __tablename__ = "pipelines"

    pipeline_id = Column(String(50), primary_key=True, index=True)
    name = Column(String(100), nullable=False)
    material = Column(String(50), nullable=False)  # Ductile Iron, Cast Iron, PVC, HDPE, Steel
    diameter_mm = Column(Float, nullable=False)
    length_meters = Column(Float, nullable=False)
    status = Column(String(20), nullable=False, default="NORMAL")  # NORMAL, WARNING, CRITICAL, OFFLINE
    geometry = Column(JSON, nullable=False)  # GeoJSON LineString geometry dict
    created_at = Column(String(50), default=utc_now_iso)
    updated_at = Column(String(50), default=utc_now_iso, onupdate=utc_now_iso)

    # Relationships
    sensors = relationship("SensorModel", back_populates="pipeline", cascade="all, delete-orphan", lazy="joined")
    alerts = relationship("AlertModel", back_populates="pipeline", lazy="select")
    tickets = relationship("TicketModel", back_populates="pipeline", lazy="select")


class SensorModel(Base):
    """Acoustic vibration / accelerometer sensor installed on a pipeline."""
    __tablename__ = "sensors"

    sensor_id = Column(String(50), primary_key=True, index=True)
    pipeline_id = Column(String(50), ForeignKey("pipelines.pipeline_id"), nullable=False)
    chainage_meters = Column(Float, nullable=False)
    latitude = Column(Float, nullable=False)
    longitude = Column(Float, nullable=False)
    installed_at = Column(String(50), default=utc_now_iso)

    # Relationship
    pipeline = relationship("PipelineModel", back_populates="sensors")


class AlertModel(Base):
    """Acoustic anomaly detection alert generated by the ML pipeline."""
    __tablename__ = "alerts"

    alert_id = Column(String(50), primary_key=True, index=True)
    pipeline_id = Column(String(50), ForeignKey("pipelines.pipeline_id"), nullable=False, index=True)
    sensor_id = Column(String(50), nullable=False)
    timestamp = Column(String(50), default=utc_now_iso, index=True)
    class_id = Column(Integer, nullable=False)  # 0..3 taxonomy
    class_label = Column(String(50), nullable=False)
    confidence = Column(Float, nullable=False)
    dominant_frequency_hz = Column(Float, nullable=False)
    sound_level_db = Column(Float, nullable=False)
    severity = Column(String(20), nullable=False)  # NONE, INFO, WARNING, CRITICAL
    estimated_chainage_meters = Column(Float, nullable=True)
    is_acknowledged = Column(Boolean, default=False, nullable=False)
    ticket_id = Column(String(50), nullable=True)

    # Relationship
    pipeline = relationship("PipelineModel", back_populates="alerts")


class TicketModel(Base):
    """Field maintenance work-order dispatched for pipeline remediation."""
    __tablename__ = "tickets"

    ticket_id = Column(String(50), primary_key=True, index=True)
    alert_id = Column(String(50), nullable=False, index=True)
    pipeline_id = Column(String(50), ForeignKey("pipelines.pipeline_id"), nullable=False, index=True)
    priority = Column(String(20), nullable=False)  # LOW, MEDIUM, HIGH, CRITICAL
    status = Column(String(20), nullable=False, default="OPEN")  # OPEN, DISPATCHED, IN_PROGRESS, RESOLVED, CLOSED
    assigned_crew = Column(String(100), nullable=True)
    description = Column(Text, nullable=False)
    location_estimate = Column(JSON, nullable=True)  # {latitude, longitude, chainage_meters}
    created_at = Column(String(50), default=utc_now_iso)
    updated_at = Column(String(50), default=utc_now_iso, onupdate=utc_now_iso)

    # Relationship
    pipeline = relationship("PipelineModel", back_populates="tickets")
